function toggleLang() {
  const cur = document.documentElement.getAttribute('data-lang')||'es';
  setLang(cur==='es'?'en':cur==='en'?'it':'es');
}
function setLang(lang) {
  document.documentElement.setAttribute('data-lang', lang);
  const btn = document.getElementById('lang-btn');
  if(btn){ btn.querySelectorAll('span').forEach(function(s){ s.classList.remove('active'); }); btn.querySelector('span[onclick="setLang(\''+lang+'\')"]').classList.add('active'); }
  const tog = document.getElementById('lang-toggle');
  if(tog){ tog.setAttribute('data-lang',lang); ['es','en','it'].forEach(function(l){ document.getElementById('lt-'+l).classList.toggle('active',lang===l); }); }
  document.querySelectorAll('[data-i18n]').forEach(function(el){
    const k = el.getAttribute('data-i18n');
    if (T[lang][k] !== undefined) el.textContent = T[lang][k];
  });
  document.querySelectorAll('[data-i18n-html]').forEach(function(el){
    const k = el.getAttribute('data-i18n-html');
    if (T[lang][k] !== undefined) el.innerHTML = T[lang][k];
  });
}
